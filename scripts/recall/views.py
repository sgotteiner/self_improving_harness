"""Everything derived from the situations store and the lesson files, rebuilt by build(), never edited by hand:
cases/history/<id>.md, cases/LESSONS.md, and lessons() (the gate's all-lessons text is built from it).
Usage: python -I scripts/recall/views.py build. Stdlib only."""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import index, mdfile, situations

HISTORY_DIR = "history"
LESSONS_FILE = "LESSONS.md"
HISTORY_HEAD = ("# {cid}: real occurrences, cleaned\n\nGenerated by scripts/recall/views.py. One block per occurrence "
                "in the case's structure; general wording, the raw words stay local. Each block is one recall example.\n\n")
LESSONS_HEAD = ("# Lessons\n\nGenerated by scripts/recall/views.py build from cases/*.md and cases/situations.jsonl; "
                "never edit by hand. Per lesson: the principle, what is right, and the situations behind it that are still active.\n")


def lessons():
    """{id: (date, lesson, right)} of every approved lesson (cases/*.md)."""
    out = {}
    for f in index.case_files():
        d = index.parse(f)
        out[d.get("id") or os.path.basename(f)[:-3]] = (d.get("date", ""), d.get("lesson", ""), d.get("right", ""))
    return out


def _write_if_changed(p, text):
    if not os.path.exists(p) or mdfile.read(p) != text:
        mdfile.write_atomic(p, text)


def pages():
    """cases/history/<id>.md for every approved lesson with active correction/gate/work lines; a page of a lesson without
    any (deleted, archived, all retired) is removed. Returns the ids with a page."""
    out, by = os.path.join(index.CASES, HISTORY_DIR), {}
    for cid in lessons():
        blocks = [index.block(r) for r in index.history_records(cid)]
        if blocks:
            by[cid] = blocks
    os.makedirs(out, exist_ok=True)
    for cid, blocks in by.items():
        _write_if_changed(os.path.join(out, cid + ".md"), HISTORY_HEAD.format(cid=cid) + "\n".join(blocks))
    for f in os.listdir(out):
        if f.endswith(".md") and f[:-3] not in by:
            os.remove(os.path.join(out, f))
    return list(by)


def lessons_md():
    """cases/LESSONS.md: every lesson with its active situations, for him to read."""
    sit = {}
    for r in situations.read():
        if r["status"] == situations.ACTIVE:
            sit.setdefault(r["lesson_id"], []).append(f"- {r['situation']} ({r['date']}, {r['source']})")
    parts = [LESSONS_HEAD]
    for cid, (_, lesson, right) in lessons().items():
        parts.append(f"## {cid}\n\n- Lesson: {lesson}\n- Right: {right}\n\nSituations:\n\n" + "\n".join(sit.get(cid, ["- (none)"])) + "\n")
    _write_if_changed(os.path.join(index.CASES, LESSONS_FILE), "\n".join(parts))


def build():
    """Regenerate every derived view from the store. Returns the ids with a history page."""
    ids = pages()
    lessons_md()
    return ids


if __name__ == "__main__" and sys.argv[1:] == ["build"]:
    print("built", len(build()), "history pages")
