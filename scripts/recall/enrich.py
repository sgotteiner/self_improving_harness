"""Write-time enrichment: the brain adds 8-12 situation descriptions per case under `enriched:` in the case file.
Only for cases whose human-written fields changed (hash in `enriched_for:`). Human fields are never touched."""
import hashlib, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import brain, index

PROMPT = """A lesson from a past mistake of an AI coding assistant is below. Write 10 short situation descriptions
(one per line, no numbering, no quotes, max 25 words each) of moments when this lesson applies. Mix two kinds:
(a) things the owner might say in his own words, casual, different wordings and vocabulary than the lesson;
(b) what the assistant itself would be doing or about to do at that moment (e.g. "about to report ...").
Output only the 10 lines.

Lesson id: {id}
Situations: {sit}
Wrong: {wrong}
Right: {right}
Lesson: {lesson}"""


def digest(d):
    s = "|".join([*d.get("situation", []), d.get("wrong", ""), d.get("right", ""), d.get("lesson", "")])
    return hashlib.sha1(s.encode("utf-8")).hexdigest()[:12]


def write(path, lines, h):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"(---\r?\n)(.*?)(\r?\n---)", text, re.S)
    head = re.sub(r"^enriched_for:.*\n?|^enriched:\s*\n(  - .*\n?)*", "", m.group(2) + "\n", flags=re.M).rstrip("\n")
    head = re.sub(r"^# generated by enrich.py.*\n?", "", head, flags=re.M).rstrip("\n")
    q = lambda s: '"' + s.replace('"', "'") + '"'
    new = head + "\n# generated by enrich.py from the fields above, do not edit by hand\nenriched_for: " + h + "\nenriched:\n"
    new += "\n".join("  - " + q(x) for x in lines)
    open(path, "w", encoding="utf-8", newline="").write(m.group(1) + new + m.group(3) + text[m.end():])


def main():
    for f in index.case_files():
        d = index.parse(f)
        h = digest(d)
        if d.get("enriched_for") == h and d.get("enriched"):
            continue
        out, tok = brain.ask(PROMPT.format(id=d["id"], sit="; ".join(d.get("situation", [])), wrong=d.get("wrong", ""),
                                           right=d.get("right", ""), lesson=d.get("lesson", "")), tag="enrich")
        lines = [re.sub(r"^[-*\d.\s]+", "", l).strip() for l in out.splitlines() if l.strip()][:12]
        write(f, lines, h)
        print(f"enriched {d['id']}: {len(lines)} lines, {tok} tokens")


if __name__ == "__main__":
    main()
