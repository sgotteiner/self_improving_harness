"""Occurrence history: every repeat of a mistake, with the raw text, in a local SQLite file (gitignored).
cases/*.md keep only `occurrences: <count>` and `last_seen: <date>`. Each occurrence also gets a cleaned version
(clean.py: general wording, no names, paths or session ids) in column clean_text; sync() writes the cleaned ones of
approved cases to cases/history/<case_id>.md, which is tracked and feeds retrieval. Raw text and transcript paths
never leave this database. Cleaning runs in a detached process after each record (a brain call is too slow for the
hook), and every later sync retries rows that failed."""
import datetime, json, os, re, sqlite3, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import index

DB = os.path.join(HERE, "history.db")
OUT = os.path.join(index.CASES, "history")


def _con():
    con = sqlite3.connect(DB)
    con.execute("CREATE TABLE IF NOT EXISTS occurrence(id INTEGER PRIMARY KEY, date TEXT, case_id TEXT, source TEXT, "
                "text TEXT, transcript TEXT)")
    if "clean_text" not in [r[1] for r in con.execute("PRAGMA table_info(occurrence)")]:
        con.execute("ALTER TABLE occurrence ADD COLUMN clean_text TEXT")
    return con


def add(case_id, source, text, transcript="", date=None):
    """source: 'gate' (output gate block, text = its reason) or 'correction' (text = his words)."""
    con = _con()
    con.execute("INSERT INTO occurrence(date, case_id, source, text, transcript) VALUES (?,?,?,?,?)",
                (date or str(datetime.date.today()), case_id, source, text, transcript or ""))
    con.commit()
    con.close()


def bump(path, date=None):
    """Set `occurrences` (+1) and `last_seen` in the case frontmatter."""
    text = open(path, encoding="utf-8").read()
    m = re.match(r"(---\r?\n)(.*?)(\r?\n---)", text, re.S)
    head = m.group(2)
    old = re.search(r"^occurrences:[ \t]*(\d+)[ \t]*$", head, re.M)
    n = int(old.group(1)) if old else 0
    head = re.sub(r"^occurrences:.*\n(?:  - .*\n?)*|^last_seen:.*\n?", "", head + "\n", flags=re.M).rstrip("\n")
    head += f"\noccurrences: {n + 1}\nlast_seen: {date or datetime.date.today()}"
    open(path, "w", encoding="utf-8", newline="").write(m.group(1) + head + m.group(3) + text[m.end():])


def record(path, source, text, transcript=""):
    add(os.path.basename(path)[:-3], source, text, transcript)
    bump(path)
    spawn_sync()


def spawn_sync():
    """Clean and publish in a detached process; never raises (the raw row is already saved)."""
    try:
        flags = (subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP) if os.name == "nt" else 0
        subprocess.Popen([sys.executable, "-I", os.path.abspath(__file__), "sync"], stdin=subprocess.DEVNULL,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, creationflags=flags, close_fds=True)
    except Exception:
        pass


def _lesson(cid):
    """The general lesson of the case the occurrence belongs to (approved or still pending); '' if unknown."""
    for d in (index.CASES, os.path.join(index.CASES, "_pending")):
        p = os.path.join(d, cid + ".md")
        if os.path.exists(p):
            return index.parse(p).get("lesson", "")
    return ""


def sync(clean_new=True):
    """Clean every row without clean_text, then rewrite cases/history/<case>.md for approved cases.
    Returns (cleaned, failed, files)."""
    import clean
    con = _con()
    done = failed = 0
    if clean_new:  # clean_text is JSON {situation, assistant_did, disliked}; older plain-sentence rows are redone
        todo = con.execute("SELECT id, case_id, source, text, transcript FROM occurrence WHERE clean_text IS NULL "
                           "OR clean_text NOT LIKE '{%' ORDER BY id").fetchall()
        for i, cid, src, text, tp in todo:
            c = clean.clean(text, src, _lesson(cid), tp)  # each lesson gets its own cleaning: his complaint is about that lesson
            if c:
                con.execute("UPDATE occurrence SET clean_text=? WHERE id=?", (json.dumps(c), i))
                con.commit()
                done += 1
            else:
                failed += 1
    rows = con.execute("SELECT date, case_id, source, clean_text FROM occurrence WHERE clean_text LIKE '{%' "
                       "ORDER BY id").fetchall()
    con.close()
    by = {}
    for d, cid, src, t in rows:
        if os.path.exists(os.path.join(index.CASES, cid + ".md")):  # pending or discarded cases are not published
            c = json.loads(t)
            by.setdefault(cid, []).append(
                f"## {d} | {src}\n- situation: {c['situation']}\n- assistant did: {c['assistant_did']}\n"
                f"- he did not like: {c['disliked']}\n- lesson: {_lesson(cid)}\n")
    os.makedirs(OUT, exist_ok=True)
    for cid, lines in by.items():
        body = (f"# {cid}: real occurrences, cleaned\n\nGenerated by scripts/recall/history.py. One block per occurrence "
                "in the case's structure; general wording, the raw words stay local. Each block is one recall example.\n\n"
                + "\n".join(lines))
        p = os.path.join(OUT, cid + ".md")
        if not os.path.exists(p) or open(p, encoding="utf-8").read() != body:
            open(p, "w", encoding="utf-8", newline="\n").write(body)
    for f in os.listdir(OUT):  # a case that was deleted takes its history file with it
        if f.endswith(".md") and f[:-3] not in by:
            os.remove(os.path.join(OUT, f))
    try:  # encode the new examples now, so the first search does not pay for them
        import embed
        embed.encode([t for cid in by for t in index.history_texts(cid)])
    except Exception:
        failed += 1
    return done, failed, len(by)


if __name__ == "__main__" and len(sys.argv) > 1 and sys.argv[1] == "sync":
    d, f, n = sync()
    print(f"cleaned {d}, failed {f}, history files {n}")
